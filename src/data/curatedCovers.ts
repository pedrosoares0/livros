export const normalizeCoverKey = (text: string): string => {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w\s]/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
};

export const getCuratedCovers = (title: string, currentCover?: string): string[] => {
  const key = normalizeCoverKey(title);
  const found = CURATED_COVERS[key] || [];
  return found.filter((c) => c !== currentCover);
};
